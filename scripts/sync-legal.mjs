// Copies the legal documents from the agency folder (projects/<app>/legal/) into the app bundle.
// Run after legal changes a document: `npm run sync-legal`. Output: src/legal/documents.generated.ts
// `--check` only compares and exits 1 when the bundled copy differs (the unit test runs it).
import assert from 'node:assert';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const legalDir = process.env.LEGAL_DIR ?? join(root, '..', '..', 'legal');

const DOCS = {
  terms: { file: 'terms.md', title: 'Términos y condiciones' },
  privacy: { file: 'privacy-policy.md', title: 'Política de privacidad' },
  cookies: { file: 'cookie-policy.md', title: 'Datos y cookies' },
  refunds: { file: 'refund-policy.md', title: 'Reintegros' },
  teacherChat: { file: 'teacher-chat-policy.md', title: 'Política de uso del chat' },
};

/** Drops internal lines (draft banner, HTML comments, ids) and keeps only "Versión x · fecha" of the version line. */
export function clean(md) {
  return md
    .replace(/\r\n/g, '\n')
    .replace(/<!--[\s\S]*?-->/g, '')
    .split('\n')
    .filter((l) => !l.startsWith('> **BORRADOR') && !l.startsWith('Identificador en `legal_documents`'))
    .map((l) => l.replace(/^\*\*(Versión [\d.]+ · [\d/]+)\*\*.*$/, '$1'))
    .join('\n')
    .replace(/^# .*\n/m, '')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

/** The version consent records point at: the `legal_documents` id line (it may sit in a hidden comment), else the visible "Versión x" line. */
export function documentVersion(md) {
  const version = md.match(/versión `([\d.]+)`/)?.[1] ?? md.match(/\*\*Versión ([\d.]+) ·/)?.[1];
  if (!version) throw new Error('Legal document has no version line');
  return version;
}

assert.equal(clean('> **BORRADOR x**\n\n# T\n\n**Versión 1.9 · 04/11/2026** (cambios)\nIdentificador en `legal_documents`: `terms`\n\nHola'), 'Versión 1.9 · 04/11/2026\n\nHola');
assert.equal(clean('> **BORRADOR x**\r\n\r\n# T\r\n\r\n<!-- v -->\r\n\r\nHola\r\n'), 'Hola');
assert.equal(documentVersion('<!-- `privacy_policy` · versión `1.20` · 16/11/2026 -->'), '1.20');
assert.equal(documentVersion('**Versión 1.8 · 07/11/2026** (cambios)'), '1.8');

const checkOnly = process.argv.includes('--check');
const outputFile = join(root, 'src', 'legal', 'documents.generated.ts');

if (!existsSync(legalDir)) {
  console.error(`Legal folder not found: ${legalDir}`);
  process.exit(1);
}

const out = {};
for (const [key, { file, title }] of Object.entries(DOCS)) {
  const markdown = readFileSync(join(legalDir, file), 'utf8');
  out[key] = { title, version: documentVersion(markdown), body: clean(markdown) };
}

const generated =
  `// Generated by scripts/sync-legal.mjs from projects/i-love-my-kinder/legal/. Do not edit by hand.\n` +
  `export const LEGAL_DOCUMENTS = ${JSON.stringify(out, null, 2)} as const;\n\n` +
  `export type LegalDocKey = keyof typeof LEGAL_DOCUMENTS;\n`;
const current = existsSync(outputFile) ? readFileSync(outputFile, 'utf8').replace(/\r\n/g, '\n') : '';

if (checkOnly) {
  if (current !== generated) {
    console.error(`Out of date: src/legal/documents.generated.ts differs from ${legalDir}. Run npm run sync-legal.`);
    process.exit(1);
  }
  console.log('src/legal/documents.generated.ts is up to date');
} else {
  writeFileSync(outputFile, generated);
  console.log(`Synced ${Object.keys(out).length} legal documents from ${legalDir}`);
}
